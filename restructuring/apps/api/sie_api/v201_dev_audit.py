"""B06: append-only DEV audit ledger (SQLite); NOT production trust boundary.

Triggers capture all successful DB writes within their originating transaction,
including batch and clone; rollback removes both domain changes and events.
Hash detects accidental corruption, not privileged filesystem modifications.
"""
from __future__ import annotations

import hashlib
import sqlite3

EVENT_TABLES = ("projects","revisions","rooms","loads","circuits","links")


def digest(event_type, actor, project, revision, entity, occurred_at):
    blob = "\x1f".join("" if value is None else str(value)
                     for value in (event_type,actor,project,revision,entity,occurred_at))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def register(db: sqlite3.Connection) -> None:
    db.create_function("sie_dev_audit_sha256", 6, digest, deterministic=True)


def install(db: sqlite3.Connection) -> None:
    db.executescript("""
    CREATE TABLE IF NOT EXISTS v201_audit_events(
      sequence INTEGER PRIMARY KEY AUTOINCREMENT,
      project_id TEXT NOT NULL, revision_id TEXT,
      actor_id TEXT NOT NULL, event_type TEXT NOT NULL,
      entity_id TEXT NOT NULL, occurred_at TEXT NOT NULL,
      event_sha256 TEXT NOT NULL);
    CREATE INDEX IF NOT EXISTS v201_audit_project_seq_idx
      ON v201_audit_events(project_id,sequence);
    CREATE TRIGGER IF NOT EXISTS sie_dev_audit_no_update
      BEFORE UPDATE ON v201_audit_events BEGIN
      SELECT RAISE(ABORT,'audit append-only');
    END;
    CREATE TRIGGER IF NOT EXISTS sie_dev_audit_no_delete
      BEFORE DELETE ON v201_audit_events BEGIN
      SELECT RAISE(ABORT,'audit append-only');
    END;
    """)
    for table in EVENT_TABLES:
        sql_table = f"v201_{table}"
        for verb in ("INSERT","UPDATE","DELETE"):
            target = "OLD" if verb=="DELETE" else "NEW"
            if table=="projects":
                actor=f"{target}.owner"
                project=f"{target}.id"
                revision="NULL"
            else:
                project=f"{target}.project_id"
                revision=f"{target}.id" if table=="revisions" else f"{target}.revision_id"
                actor=f"(SELECT owner FROM v201_projects WHERE id={target}.project_id)"
            event=f"{table[:-1] if table.endswith('s') else table}.{dict(INSERT='created',UPDATE='updated',DELETE='deleted')[verb]}"
            if table=="revisions" and verb=="UPDATE":
                event=f"revision."  # state transitions recorded independently
                event_expr=f"('revision.' || lower({target}.state))"
            else:
                event_expr="'"+event+"'"
            entity=f"{target}.id"
            # timestamp generated by SQLite server during the statement; no payload details,
            # personal data, JWT, or credential content are inserted into audit.
            ts="strftime('%Y-%m-%dT%H:%M:%fZ','now')"
            values=f"{project},{revision},{actor},{event_expr},{entity},{ts}"
            # Avoid referencing subqueries/aliases in trigger scalar UDF that are unavailable.
            db.execute(f"""CREATE TRIGGER IF NOT EXISTS sie_dev_audit_{table}_{verb.lower()}
              AFTER {verb} ON {sql_table} BEGIN
              INSERT INTO v201_audit_events(
                project_id,revision_id,actor_id,event_type,entity_id,occurred_at,event_sha256)
              VALUES ({values},sie_dev_audit_sha256({values}));
              END""")
